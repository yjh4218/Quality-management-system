-- 1. 교육과정 마스터 테이블 (training_courses)
CREATE TABLE IF NOT EXISTS training_courses (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    version BIGINT DEFAULT 0,
    course_code VARCHAR(50) NOT NULL UNIQUE,
    course_name VARCHAR(200) NOT NULL,
    category VARCHAR(30) NOT NULL,
    target_family VARCHAR(30) NOT NULL DEFAULT 'COMMON',
    target_audience VARCHAR(200),
    cycle_months INT NOT NULL DEFAULT 12,
    passing_score INT NOT NULL DEFAULT 70,
    training_hours DOUBLE PRECISION DEFAULT 2.0,
    is_required BOOLEAN NOT NULL DEFAULT true,
    instructor VARCHAR(100),
    description TEXT,
    material_url VARCHAR(500),
    status VARCHAR(20) NOT NULL DEFAULT 'ACTIVE',
    is_deleted BOOLEAN NOT NULL DEFAULT false,
    deleted_at TIMESTAMP,
    created_at TIMESTAMP,
    updated_at TIMESTAMP,
    created_by VARCHAR(100),
    updated_by VARCHAR(100)
);

CREATE INDEX IF NOT EXISTS idx_tc_course_code ON training_courses(course_code);
CREATE INDEX IF NOT EXISTS idx_tc_category ON training_courses(category);
CREATE INDEX IF NOT EXISTS idx_tc_target_family ON training_courses(target_family);
CREATE INDEX IF NOT EXISTS idx_tc_status ON training_courses(status);
CREATE INDEX IF NOT EXISTS idx_tc_is_required ON training_courses(is_required);

-- 2. 교육이수 및 평가 기록 테이블 (training_records)
CREATE TABLE IF NOT EXISTS training_records (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    version BIGINT DEFAULT 0,
    record_no VARCHAR(50) NOT NULL UNIQUE,
    course_id BIGINT NOT NULL,
    course_code VARCHAR(50) NOT NULL,
    course_name VARCHAR(200) NOT NULL,
    category VARCHAR(30) NOT NULL,
    target_family VARCHAR(30) NOT NULL DEFAULT 'COMMON',
    user_id BIGINT,
    username VARCHAR(100) NOT NULL,
    trainee_name VARCHAR(100) NOT NULL,
    department VARCHAR(100),
    position VARCHAR(100),
    training_date DATE NOT NULL,
    expiry_date DATE,
    completion_status VARCHAR(30) NOT NULL DEFAULT 'SCHEDULED',
    score INT,
    is_passed BOOLEAN DEFAULT false,
    evaluation_method VARCHAR(30) DEFAULT 'WRITTEN_TEST',
    effectiveness_evaluation VARCHAR(30) DEFAULT 'PENDING',
    effectiveness_evaluator VARCHAR(100),
    effectiveness_date DATE,
    effectiveness_notes TEXT,
    certificate_url VARCHAR(500),
    certificate_file_name VARCHAR(255),
    certificate_file_size BIGINT,
    remarks TEXT,
    is_deleted BOOLEAN NOT NULL DEFAULT false,
    deleted_at TIMESTAMP,
    created_at TIMESTAMP,
    updated_at TIMESTAMP,
    created_by VARCHAR(100),
    updated_by VARCHAR(100)
);

CREATE INDEX IF NOT EXISTS idx_tr_record_no ON training_records(record_no);
CREATE INDEX IF NOT EXISTS idx_tr_course_id ON training_records(course_id);
CREATE INDEX IF NOT EXISTS idx_tr_course_code ON training_records(course_code);
CREATE INDEX IF NOT EXISTS idx_tr_username ON training_records(username);
CREATE INDEX IF NOT EXISTS idx_tr_department ON training_records(department);
CREATE INDEX IF NOT EXISTS idx_tr_status ON training_records(completion_status);
CREATE INDEX IF NOT EXISTS idx_tr_training_date ON training_records(training_date);
CREATE INDEX IF NOT EXISTS idx_tr_expiry_date ON training_records(expiry_date);

-- 3. 직무 자격 적격성 테이블 (user_qualifications - Competence Matrix)
CREATE TABLE IF NOT EXISTS user_qualifications (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    version BIGINT DEFAULT 0,
    user_id BIGINT,
    username VARCHAR(100) NOT NULL,
    user_name VARCHAR(100) NOT NULL,
    department VARCHAR(100),
    position VARCHAR(100),
    qualification_name VARCHAR(150) NOT NULL,
    qualification_type VARCHAR(30) NOT NULL,
    qualification_status VARCHAR(30) NOT NULL DEFAULT 'QUALIFIED',
    certified_date DATE NOT NULL,
    expiry_date DATE,
    required_course_code VARCHAR(50),
    certificate_number VARCHAR(100),
    authorizer_name VARCHAR(100),
    remarks TEXT,
    is_deleted BOOLEAN NOT NULL DEFAULT false,
    deleted_at TIMESTAMP,
    created_at TIMESTAMP,
    updated_at TIMESTAMP,
    created_by VARCHAR(100),
    updated_by VARCHAR(100)
);

CREATE INDEX IF NOT EXISTS idx_uq_username ON user_qualifications(username);
CREATE INDEX IF NOT EXISTS idx_uq_department ON user_qualifications(department);
CREATE INDEX IF NOT EXISTS idx_uq_type ON user_qualifications(qualification_type);
CREATE INDEX IF NOT EXISTS idx_uq_status ON user_qualifications(qualification_status);
CREATE INDEX IF NOT EXISTS idx_uq_expiry_date ON user_qualifications(expiry_date);

