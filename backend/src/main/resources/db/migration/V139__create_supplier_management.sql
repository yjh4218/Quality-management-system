-- 1. 공급업체 품질 적격성 마스터 테이블 (supplier_qualifications)
CREATE TABLE IF NOT EXISTS supplier_qualifications (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    version BIGINT DEFAULT 0,
    supplier_code VARCHAR(50) NOT NULL UNIQUE,
    manufacturer_id BIGINT NOT NULL,
    supplier_type VARCHAR(50) NOT NULL DEFAULT 'RAW_MATERIAL',
    approval_status VARCHAR(50) NOT NULL DEFAULT 'PENDING_QUALIFICATION',
    supplier_grade VARCHAR(20) NOT NULL DEFAULT 'GRADE_B',
    risk_level VARCHAR(20) DEFAULT 'MEDIUM',
    iso_certifications VARCHAR(255),
    business_registration_number VARCHAR(50),
    initial_approval_date DATE,
    last_audit_date DATE,
    next_evaluation_date DATE,
    scope_of_supply TEXT,
    qualification_notes TEXT,
    approved_by VARCHAR(100),
    
    -- 감사추적 메타데이터
    is_deleted BOOLEAN NOT NULL DEFAULT false,
    deleted_at TIMESTAMP,
    created_by VARCHAR(100),
    updated_by VARCHAR(100),
    created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    
    CONSTRAINT fk_sup_qual_manufacturer FOREIGN KEY (manufacturer_id) REFERENCES manufacturers(id) ON DELETE CASCADE
);

-- 2. 공급업체 정기 종합평가 테이블 (supplier_evaluations)
CREATE TABLE IF NOT EXISTS supplier_evaluations (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    version BIGINT DEFAULT 0,
    qualification_id BIGINT NOT NULL,
    evaluation_year INT NOT NULL,
    evaluation_period VARCHAR(20) NOT NULL DEFAULT 'ANNUAL',
    quality_score INT NOT NULL DEFAULT 0,
    delivery_score INT NOT NULL DEFAULT 0,
    compliance_score INT NOT NULL DEFAULT 0,
    service_score INT NOT NULL DEFAULT 0,
    total_score INT NOT NULL DEFAULT 0,
    evaluation_grade VARCHAR(20) NOT NULL DEFAULT 'GRADE_B',
    evaluation_date DATE NOT NULL,
    evaluator_name VARCHAR(100) NOT NULL,
    evaluator_department VARCHAR(100),
    evaluation_summary TEXT,
    corrective_action_required BOOLEAN DEFAULT false,
    action_details TEXT,
    capa_id BIGINT,
    
    -- 감사추적 메타데이터
    is_deleted BOOLEAN NOT NULL DEFAULT false,
    deleted_at TIMESTAMP,
    created_by VARCHAR(100),
    updated_by VARCHAR(100),
    created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    
    CONSTRAINT fk_sup_eval_qualification FOREIGN KEY (qualification_id) REFERENCES supplier_qualifications(id) ON DELETE CASCADE
);

-- 3. 품질협약서 마스터 테이블 (quality_agreements - QAA)
CREATE TABLE IF NOT EXISTS quality_agreements (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    version BIGINT DEFAULT 0,
    agreement_number VARCHAR(50) NOT NULL UNIQUE,
    manufacturer_id BIGINT NOT NULL,
    qualification_id BIGINT,
    title VARCHAR(255) NOT NULL,
    agreement_type VARCHAR(50) NOT NULL DEFAULT 'CONTRACT_MANUFACTURING',
    effective_date DATE NOT NULL,
    expiry_date DATE NOT NULL,
    retention_expiry_date DATE NOT NULL,
    auto_renewal BOOLEAN DEFAULT false,
    renewal_notice_days INT DEFAULT 60,
    agreement_status VARCHAR(30) NOT NULL DEFAULT 'ACTIVE',
    change_notification_obligation TEXT,
    audit_rights_confirmed BOOLEAN DEFAULT true,
    agreement_doc_url VARCHAR(500),
    document_file_name VARCHAR(255),
    notes TEXT,
    
    -- 감사추적 메타데이터
    is_deleted BOOLEAN NOT NULL DEFAULT false,
    deleted_at TIMESTAMP,
    created_by VARCHAR(100),
    updated_by VARCHAR(100),
    created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    
    CONSTRAINT fk_qaa_manufacturer FOREIGN KEY (manufacturer_id) REFERENCES manufacturers(id) ON DELETE CASCADE,
    CONSTRAINT fk_qaa_qualification FOREIGN KEY (qualification_id) REFERENCES supplier_qualifications(id) ON DELETE SET NULL
);

-- 4. 성능 최적화 B-Tree 인덱스 12종 생성
CREATE INDEX IF NOT EXISTS idx_sup_qual_manufacturer ON supplier_qualifications (manufacturer_id);
CREATE INDEX IF NOT EXISTS idx_sup_qual_status ON supplier_qualifications (approval_status);
CREATE INDEX IF NOT EXISTS idx_sup_qual_grade ON supplier_qualifications (supplier_grade);
CREATE INDEX IF NOT EXISTS idx_sup_qual_type ON supplier_qualifications (supplier_type);
CREATE INDEX IF NOT EXISTS idx_sup_qual_deleted ON supplier_qualifications (is_deleted);

CREATE INDEX IF NOT EXISTS idx_sup_eval_qual ON supplier_evaluations (qualification_id);
CREATE INDEX IF NOT EXISTS idx_sup_eval_year_period ON supplier_evaluations (evaluation_year, evaluation_period);
CREATE INDEX IF NOT EXISTS idx_sup_eval_grade ON supplier_evaluations (evaluation_grade);
CREATE INDEX IF NOT EXISTS idx_sup_eval_deleted ON supplier_evaluations (is_deleted);

CREATE INDEX IF NOT EXISTS idx_qaa_manufacturer ON quality_agreements (manufacturer_id);
CREATE INDEX IF NOT EXISTS idx_qaa_status ON quality_agreements (agreement_status);
CREATE INDEX IF NOT EXISTS idx_qaa_expiry ON quality_agreements (expiry_date);
CREATE INDEX IF NOT EXISTS idx_qaa_retention ON quality_agreements (retention_expiry_date);
CREATE INDEX IF NOT EXISTS idx_qaa_deleted ON quality_agreements (is_deleted);

