-- 1. 위험성 평가 파일 테이블 (risk_assessments)
CREATE TABLE IF NOT EXISTS risk_assessments (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    version BIGINT DEFAULT 0,
    assessment_no VARCHAR(50) NOT NULL UNIQUE,
    title VARCHAR(200) NOT NULL,
    product_id BIGINT,
    product_code VARCHAR(50),
    product_name VARCHAR(200) NOT NULL,
    target_family VARCHAR(30) NOT NULL DEFAULT 'MEDICAL_DEVICE',
    risk_phase VARCHAR(30) NOT NULL DEFAULT 'DESIGN',
    version_tag VARCHAR(20) NOT NULL DEFAULT '1.0',
    status VARCHAR(20) NOT NULL DEFAULT 'DRAFT',
    author VARCHAR(100) NOT NULL,
    reviewer VARCHAR(100),
    approver VARCHAR(100),
    assessment_date DATE NOT NULL,
    approval_date DATE,
    scope_description TEXT,
    overall_residual_risk_acceptable BOOLEAN DEFAULT true,
    overall_conclusion TEXT,
    is_deleted BOOLEAN NOT NULL DEFAULT false,
    deleted_at TIMESTAMP,
    created_at TIMESTAMP,
    updated_at TIMESTAMP,
    created_by VARCHAR(100),
    updated_by VARCHAR(100)
);

CREATE INDEX IF NOT EXISTS idx_ra_assessment_no ON risk_assessments(assessment_no);
CREATE INDEX IF NOT EXISTS idx_ra_product_name ON risk_assessments(product_name);
CREATE INDEX IF NOT EXISTS idx_ra_risk_phase ON risk_assessments(risk_phase);
CREATE INDEX IF NOT EXISTS idx_ra_status ON risk_assessments(status);
CREATE INDEX IF NOT EXISTS idx_ra_target_family ON risk_assessments(target_family);
CREATE INDEX IF NOT EXISTS idx_ra_is_deleted ON risk_assessments(is_deleted);

-- 2. 위해요인 및 FMEA 위험 통제 조치 테이블 (risk_hazard_items)
CREATE TABLE IF NOT EXISTS risk_hazard_items (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    version BIGINT DEFAULT 0,
    assessment_id BIGINT NOT NULL,
    item_no VARCHAR(50) NOT NULL,
    category VARCHAR(30) NOT NULL DEFAULT 'ELECTRICAL',
    hazard VARCHAR(255) NOT NULL,
    hazardous_situation TEXT NOT NULL,
    harm TEXT NOT NULL,
    initial_severity INT NOT NULL DEFAULT 3,
    initial_probability INT NOT NULL DEFAULT 3,
    initial_risk_score INT NOT NULL DEFAULT 9,
    initial_acceptability VARCHAR(30) NOT NULL DEFAULT 'ALARP',
    control_category VARCHAR(30) NOT NULL DEFAULT 'INHERENT_SAFETY',
    control_measures TEXT NOT NULL,
    control_status VARCHAR(30) NOT NULL DEFAULT 'COMPLETED',
    verification_method VARCHAR(255),
    verification_result VARCHAR(50) DEFAULT 'PASS',
    residual_severity INT NOT NULL DEFAULT 2,
    residual_probability INT NOT NULL DEFAULT 1,
    residual_risk_score INT NOT NULL DEFAULT 2,
    residual_acceptability VARCHAR(30) NOT NULL DEFAULT 'ACCEPTABLE',
    benefit_risk_needed BOOLEAN DEFAULT false,
    benefit_risk_summary TEXT,
    remarks TEXT,
    is_deleted BOOLEAN NOT NULL DEFAULT false,
    deleted_at TIMESTAMP,
    created_at TIMESTAMP,
    updated_at TIMESTAMP,
    created_by VARCHAR(100),
    updated_by VARCHAR(100),
    CONSTRAINT fk_rhi_assessment FOREIGN KEY (assessment_id) REFERENCES risk_assessments(id) ON DELETE CASCADE
);

CREATE INDEX IF NOT EXISTS idx_rhi_assessment_id ON risk_hazard_items(assessment_id);
CREATE INDEX IF NOT EXISTS idx_rhi_item_no ON risk_hazard_items(item_no);
CREATE INDEX IF NOT EXISTS idx_rhi_category ON risk_hazard_items(category);
CREATE INDEX IF NOT EXISTS idx_rhi_init_accept ON risk_hazard_items(initial_acceptability);
CREATE INDEX IF NOT EXISTS idx_rhi_res_accept ON risk_hazard_items(residual_acceptability);
CREATE INDEX IF NOT EXISTS idx_rhi_ctrl_status ON risk_hazard_items(control_status);
CREATE INDEX IF NOT EXISTS idx_rhi_is_deleted ON risk_hazard_items(is_deleted);

