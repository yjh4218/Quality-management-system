-- 1. 설계개발 프로젝트 마스터 테이블 (design_projects)
CREATE TABLE IF NOT EXISTS design_projects (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    version BIGINT DEFAULT 0,
    project_code VARCHAR(50) NOT NULL UNIQUE,
    project_name VARCHAR(200) NOT NULL,
    medical_device_id BIGINT,
    target_device_name VARCHAR(200) NOT NULL,
    device_classification VARCHAR(30) NOT NULL DEFAULT 'CLASS_II',
    project_leader VARCHAR(100) NOT NULL,
    department VARCHAR(100) NOT NULL,
    start_date DATE NOT NULL,
    target_completion_date DATE NOT NULL,
    actual_completion_date DATE,
    current_phase VARCHAR(30) NOT NULL DEFAULT 'PLANNING',
    status VARCHAR(30) NOT NULL DEFAULT 'ACTIVE',
    dhf_number VARCHAR(50) NOT NULL UNIQUE,
    dhf_status VARCHAR(30) NOT NULL DEFAULT 'OPEN',
    risk_assessment_id BIGINT,
    description TEXT,
    is_deleted BOOLEAN NOT NULL DEFAULT false,
    deleted_at TIMESTAMP,
    created_at TIMESTAMP,
    updated_at TIMESTAMP,
    created_by VARCHAR(100),
    updated_by VARCHAR(100)
);

CREATE INDEX IF NOT EXISTS idx_dp_project_code ON design_projects(project_code);
CREATE INDEX IF NOT EXISTS idx_dp_dhf_number ON design_projects(dhf_number);
CREATE INDEX IF NOT EXISTS idx_dp_current_phase ON design_projects(current_phase);
CREATE INDEX IF NOT EXISTS idx_dp_status ON design_projects(status);
CREATE INDEX IF NOT EXISTS idx_dp_dhf_status ON design_projects(dhf_status);
CREATE INDEX IF NOT EXISTS idx_dp_is_deleted ON design_projects(is_deleted);

-- 2. 설계통제 항목 및 추적성 테이블 (design_control_items)
CREATE TABLE IF NOT EXISTS design_control_items (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    version BIGINT DEFAULT 0,
    project_id BIGINT NOT NULL,
    item_code VARCHAR(50) NOT NULL,
    item_type VARCHAR(30) NOT NULL DEFAULT 'DESIGN_INPUT',
    title VARCHAR(255) NOT NULL,
    specification TEXT NOT NULL,
    acceptance_criteria TEXT,
    verification_method VARCHAR(255),
    verification_result VARCHAR(30) DEFAULT 'PENDING',
    result_summary TEXT,
    evidence_doc_url VARCHAR(500),
    parent_input_item_code VARCHAR(50),
    risk_hazard_code VARCHAR(50),
    responsible_person VARCHAR(100) NOT NULL,
    status VARCHAR(30) NOT NULL DEFAULT 'DRAFT',
    is_deleted BOOLEAN NOT NULL DEFAULT false,
    deleted_at TIMESTAMP,
    created_at TIMESTAMP,
    updated_at TIMESTAMP,
    created_by VARCHAR(100),
    updated_by VARCHAR(100),
    CONSTRAINT fk_dci_project FOREIGN KEY (project_id) REFERENCES design_projects(id) ON DELETE CASCADE
);

CREATE INDEX IF NOT EXISTS idx_dci_project_id ON design_control_items(project_id);
CREATE INDEX IF NOT EXISTS idx_dci_item_code ON design_control_items(item_code);
CREATE INDEX IF NOT EXISTS idx_dci_item_type ON design_control_items(item_type);
CREATE INDEX IF NOT EXISTS idx_dci_ver_result ON design_control_items(verification_result);
CREATE INDEX IF NOT EXISTS idx_dci_parent_input ON design_control_items(parent_input_item_code);
CREATE INDEX IF NOT EXISTS idx_dci_risk_hazard ON design_control_items(risk_hazard_code);
CREATE INDEX IF NOT EXISTS idx_dci_is_deleted ON design_control_items(is_deleted);

-- 3. 설계 심의 및 단계 게이트 기록 테이블 (design_review_records)
CREATE TABLE IF NOT EXISTS design_review_records (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    version BIGINT DEFAULT 0,
    project_id BIGINT NOT NULL,
    review_number VARCHAR(50) NOT NULL,
    review_phase VARCHAR(30) NOT NULL DEFAULT 'PLANNING',
    review_title VARCHAR(200) NOT NULL,
    review_date DATE NOT NULL,
    attendees VARCHAR(500) NOT NULL,
    review_summary TEXT NOT NULL,
    action_items TEXT,
    gate_decision VARCHAR(30) NOT NULL DEFAULT 'GO',
    approval_document_id BIGINT,
    is_deleted BOOLEAN NOT NULL DEFAULT false,
    deleted_at TIMESTAMP,
    created_at TIMESTAMP,
    updated_at TIMESTAMP,
    created_by VARCHAR(100),
    updated_by VARCHAR(100),
    CONSTRAINT fk_drr_project FOREIGN KEY (project_id) REFERENCES design_projects(id) ON DELETE CASCADE
);

CREATE INDEX IF NOT EXISTS idx_drr_project_id ON design_review_records(project_id);
CREATE INDEX IF NOT EXISTS idx_drr_review_phase ON design_review_records(review_phase);
CREATE INDEX IF NOT EXISTS idx_drr_gate_decision ON design_review_records(gate_decision);
CREATE INDEX IF NOT EXISTS idx_drr_is_deleted ON design_review_records(is_deleted);

