-- 1. 부적합 보고서 마스터 테이블 (ncr_reports)
CREATE TABLE IF NOT EXISTS ncr_reports (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    version BIGINT DEFAULT 0,
    ncr_number VARCHAR(50) NOT NULL UNIQUE,
    title VARCHAR(255) NOT NULL,
    stage VARCHAR(50) NOT NULL DEFAULT 'INCOMING_INSPECTION',
    severity VARCHAR(30) NOT NULL DEFAULT 'MAJOR',
    status VARCHAR(50) NOT NULL DEFAULT 'SUBMITTED',
    source_type VARCHAR(50) DEFAULT 'WMS_INBOUND',
    source_record_id BIGINT,
    item_code VARCHAR(100) NOT NULL,
    product_name VARCHAR(255) NOT NULL,
    lot_number VARCHAR(100),
    affected_quantity DECIMAL(15, 3) DEFAULT 0,
    unit VARCHAR(30) DEFAULT 'EA',
    supplier_name VARCHAR(150),
    occurred_date DATE NOT NULL,
    discovered_by VARCHAR(100),
    defect_type VARCHAR(100),
    defect_description TEXT NOT NULL,
    immediate_action TEXT,
    quarantine_status VARCHAR(50) NOT NULL DEFAULT 'QUARANTINED',
    quarantine_location VARCHAR(150),
    root_cause_analysis TEXT,
    disposition_type VARCHAR(50) NOT NULL DEFAULT 'PENDING',
    disposition_details TEXT,
    disposition_approved_by VARCHAR(100),
    disposition_approved_at TIMESTAMP,
    rework_instructions TEXT,
    concession_justification TEXT,
    capa_required BOOLEAN NOT NULL DEFAULT false,
    capa_status VARCHAR(50) NOT NULL DEFAULT 'NOT_REQUIRED',
    capa_reference_id VARCHAR(50),
    capa_rationale TEXT,
    closed_by VARCHAR(100),
    closed_at TIMESTAMP,
    closure_remarks TEXT,
    
    -- 감사추적 메타데이터
    is_deleted BOOLEAN NOT NULL DEFAULT false,
    deleted_at TIMESTAMP,
    created_by VARCHAR(100),
    updated_by VARCHAR(100),
    created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP
);

-- 2. 부적합 조치 과제 및 재작업 실행 테이블 (ncr_action_items)
CREATE TABLE IF NOT EXISTS ncr_action_items (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    version BIGINT DEFAULT 0,
    ncr_id BIGINT NOT NULL,
    item_order INT DEFAULT 1,
    action_type VARCHAR(50) NOT NULL DEFAULT 'CORRECTION',
    description TEXT NOT NULL,
    assignee VARCHAR(100) NOT NULL,
    due_date DATE,
    completed_at TIMESTAMP,
    status VARCHAR(50) NOT NULL DEFAULT 'PENDING',
    verification_result VARCHAR(50) DEFAULT 'PENDING',
    verified_by VARCHAR(100),
    verified_at TIMESTAMP,
    verification_notes TEXT,
    
    -- 감사추적 메타데이터
    is_deleted BOOLEAN NOT NULL DEFAULT false,
    deleted_at TIMESTAMP,
    created_by VARCHAR(100),
    updated_by VARCHAR(100),
    created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    
    CONSTRAINT fk_ncr_action_report FOREIGN KEY (ncr_id) REFERENCES ncr_reports(id) ON DELETE CASCADE
);

-- 인덱스 생성
CREATE INDEX IF NOT EXISTS idx_ncr_num ON ncr_reports(ncr_number);
CREATE INDEX IF NOT EXISTS idx_ncr_stage ON ncr_reports(stage);
CREATE INDEX IF NOT EXISTS idx_ncr_severity ON ncr_reports(severity);
CREATE INDEX IF NOT EXISTS idx_ncr_status ON ncr_reports(status);
CREATE INDEX IF NOT EXISTS idx_ncr_quarantine ON ncr_reports(quarantine_status);
CREATE INDEX IF NOT EXISTS idx_ncr_lot ON ncr_reports(lot_number);
CREATE INDEX IF NOT EXISTS idx_ncr_item ON ncr_reports(item_code);
CREATE INDEX IF NOT EXISTS idx_ncr_source ON ncr_reports(source_type, source_record_id);
CREATE INDEX IF NOT EXISTS idx_ncr_deleted ON ncr_reports(is_deleted);

CREATE INDEX IF NOT EXISTS idx_ncr_action_ncr ON ncr_action_items(ncr_id);
CREATE INDEX IF NOT EXISTS idx_ncr_action_status ON ncr_action_items(status);
CREATE INDEX IF NOT EXISTS idx_ncr_action_deleted ON ncr_action_items(is_deleted);

