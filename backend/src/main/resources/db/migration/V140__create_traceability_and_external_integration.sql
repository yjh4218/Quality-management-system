-- 1. 배치/LOT 마스터 테이블 (traceability_batches)
CREATE TABLE IF NOT EXISTS traceability_batches (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    version BIGINT DEFAULT 0,
    batch_number VARCHAR(100) NOT NULL UNIQUE,
    batch_stage VARCHAR(50) NOT NULL DEFAULT 'RAW_MATERIAL',
    item_code VARCHAR(100) NOT NULL,
    item_name VARCHAR(255) NOT NULL,
    item_category VARCHAR(50) NOT NULL DEFAULT 'COSMETICS',
    specification VARCHAR(255),
    quantity DECIMAL(15, 3) NOT NULL DEFAULT 0.000,
    remaining_quantity DECIMAL(15, 3) NOT NULL DEFAULT 0.000,
    unit VARCHAR(20) NOT NULL DEFAULT 'EA',
    manufacturing_date DATE,
    expiration_date DATE,
    supplier_or_manufacturer VARCHAR(255),
    manufacturing_line VARCHAR(100),
    storage_location VARCHAR(100),
    quality_status VARCHAR(50) NOT NULL DEFAULT 'QUARANTINE',
    coa_number VARCHAR(100),
    coa_file_url VARCHAR(500),
    notes TEXT,
    
    -- 감사추적 메타데이터
    is_deleted BOOLEAN NOT NULL DEFAULT false,
    deleted_at TIMESTAMP,
    created_by VARCHAR(100),
    updated_by VARCHAR(100),
    created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP
);

-- 2. 양방향 투입 연결 관계 테이블 (traceability_links)
CREATE TABLE IF NOT EXISTS traceability_links (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    version BIGINT DEFAULT 0,
    parent_batch_number VARCHAR(100) NOT NULL,
    child_batch_number VARCHAR(100) NOT NULL,
    process_step VARCHAR(100) NOT NULL DEFAULT '투입조제',
    input_quantity DECIMAL(15, 3) NOT NULL DEFAULT 0.000,
    input_unit VARCHAR(20) NOT NULL DEFAULT 'EA',
    yield_ratio DECIMAL(7, 2) DEFAULT 100.00,
    link_date DATE NOT NULL,
    operator_name VARCHAR(100),
    notes TEXT,
    
    -- 감사추적 메타데이터
    is_deleted BOOLEAN NOT NULL DEFAULT false,
    deleted_at TIMESTAMP,
    created_by VARCHAR(100),
    updated_by VARCHAR(100),
    created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP
);

-- 3. 외부 시스템 연동 및 수기 대사 로그 테이블 (external_integration_logs)
CREATE TABLE IF NOT EXISTS external_integration_logs (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    version BIGINT DEFAULT 0,
    log_number VARCHAR(100) NOT NULL UNIQUE,
    system_type VARCHAR(50) NOT NULL DEFAULT 'ERP',
    interface_type VARCHAR(50) NOT NULL DEFAULT 'INVENTORY_RECONCILIATION',
    transfer_protocol VARCHAR(50) NOT NULL DEFAULT 'REST_API',
    status VARCHAR(50) NOT NULL DEFAULT 'PENDING',
    target_batch_number VARCHAR(100),
    request_payload TEXT,
    response_payload TEXT,
    record_count INT DEFAULT 1,
    discrepancy_count INT DEFAULT 0,
    reconciled_by VARCHAR(100),
    reconciliation_notes TEXT,
    reconciled_at TIMESTAMP,
    
    -- 감사추적 메타데이터
    is_deleted BOOLEAN NOT NULL DEFAULT false,
    deleted_at TIMESTAMP,
    created_by VARCHAR(100),
    updated_by VARCHAR(100),
    created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP
);

-- 4. 바코드 및 UDI 식별 관리 테이블 (barcode_records)
CREATE TABLE IF NOT EXISTS barcode_records (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    version BIGINT DEFAULT 0,
    barcode_value VARCHAR(255) NOT NULL UNIQUE,
    barcode_type VARCHAR(50) NOT NULL DEFAULT 'GS1_128',
    batch_number VARCHAR(100) NOT NULL,
    gtin VARCHAR(50),
    expiration_date_string VARCHAR(20),
    serial_number VARCHAR(100),
    print_count INT NOT NULL DEFAULT 0,
    status VARCHAR(50) NOT NULL DEFAULT 'ACTIVE',
    issued_by VARCHAR(100),
    
    -- 감사추적 메타데이터
    is_deleted BOOLEAN NOT NULL DEFAULT false,
    deleted_at TIMESTAMP,
    created_by VARCHAR(100),
    updated_by VARCHAR(100),
    created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP
);

-- 인덱스 생성
CREATE INDEX IF NOT EXISTS idx_trace_batch_num ON traceability_batches(batch_number);
CREATE INDEX IF NOT EXISTS idx_trace_batch_stage ON traceability_batches(batch_stage);
CREATE INDEX IF NOT EXISTS idx_trace_batch_status ON traceability_batches(quality_status);
CREATE INDEX IF NOT EXISTS idx_trace_batch_deleted ON traceability_batches(is_deleted);

CREATE INDEX IF NOT EXISTS idx_trace_link_parent ON traceability_links(parent_batch_number);
CREATE INDEX IF NOT EXISTS idx_trace_link_child ON traceability_links(child_batch_number);
CREATE INDEX IF NOT EXISTS idx_trace_link_deleted ON traceability_links(is_deleted);

CREATE INDEX IF NOT EXISTS idx_ext_log_num ON external_integration_logs(log_number);
CREATE INDEX IF NOT EXISTS idx_ext_log_system ON external_integration_logs(system_type);
CREATE INDEX IF NOT EXISTS idx_ext_log_status ON external_integration_logs(status);
CREATE INDEX IF NOT EXISTS idx_ext_log_batch ON external_integration_logs(target_batch_number);

CREATE INDEX IF NOT EXISTS idx_barcode_val ON barcode_records(barcode_value);
CREATE INDEX IF NOT EXISTS idx_barcode_batch ON barcode_records(batch_number);
CREATE INDEX IF NOT EXISTS idx_barcode_status ON barcode_records(status);

