-- 1. 통제문서 (Controlled Documents) 마스터 테이블 생성
CREATE TABLE IF NOT EXISTS controlled_documents (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    version BIGINT DEFAULT 0,
    doc_no VARCHAR(50) NOT NULL,
    title VARCHAR(255) NOT NULL,
    doc_type VARCHAR(30) NOT NULL,
    target_family VARCHAR(30) NOT NULL DEFAULT 'COMMON',
    status VARCHAR(30) NOT NULL DEFAULT 'DRAFT',
    revision_no VARCHAR(20) NOT NULL DEFAULT 'Rev. 0',
    revision_int INT NOT NULL DEFAULT 0,
    parent_document_id BIGINT,
    change_rationale TEXT,
    effective_date DATE,
    expiration_date DATE,
    department VARCHAR(100),
    author_name VARCHAR(100),
    reviewer_name VARCHAR(100),
    approver_name VARCHAR(100),
    content TEXT,
    attachment_url VARCHAR(500),
    attachment_file_name VARCHAR(255),
    attachment_file_size BIGINT,
    approval_doc_id BIGINT,
    is_deleted BOOLEAN DEFAULT false,
    deleted_at TIMESTAMP,
    created_at TIMESTAMP,
    updated_at TIMESTAMP,
    created_by VARCHAR(100),
    updated_by VARCHAR(100)
);

CREATE INDEX IF NOT EXISTS idx_cd_doc_no ON controlled_documents(doc_no);
CREATE INDEX IF NOT EXISTS idx_cd_status ON controlled_documents(status);
CREATE INDEX IF NOT EXISTS idx_cd_doc_type ON controlled_documents(doc_type);
CREATE INDEX IF NOT EXISTS idx_cd_target_family ON controlled_documents(target_family);
CREATE INDEX IF NOT EXISTS idx_cd_title ON controlled_documents(title);
CREATE INDEX IF NOT EXISTS idx_cd_parent_id ON controlled_documents(parent_document_id);

