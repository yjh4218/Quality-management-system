-- 1. 고객 불만 및 이상사례 안전성 평가 마스터 테이블 (complaint_safety_evaluations)
CREATE TABLE IF NOT EXISTS complaint_safety_evaluations (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    version BIGINT DEFAULT 0,
    evaluation_number VARCHAR(50) NOT NULL UNIQUE,
    claim_id BIGINT,
    claim_number VARCHAR(50),
    title VARCHAR(255) NOT NULL,
    product_type VARCHAR(50) NOT NULL DEFAULT 'COSMETIC',
    item_code VARCHAR(100) NOT NULL,
    product_name VARCHAR(255) NOT NULL,
    lot_number VARCHAR(100),
    is_lot_unknown BOOLEAN NOT NULL DEFAULT false,
    manufacturer VARCHAR(150),
    receipt_date DATE NOT NULL,
    evaluator_name VARCHAR(100) NOT NULL,
    evaluation_date DATE NOT NULL,
    
    -- 환자/고객 정보
    customer_name VARCHAR(100),
    customer_contact VARCHAR(100),
    patient_age INTEGER,
    patient_gender VARCHAR(20) DEFAULT 'UNKNOWN',
    
    -- 이상사례 증상 및 진료 내역
    adverse_event_category VARCHAR(100) NOT NULL,
    symptom_description TEXT NOT NULL,
    onset_days INTEGER DEFAULT 0,
    medical_treatment_given BOOLEAN NOT NULL DEFAULT false,
    treatment_details TEXT,
    
    -- 중대성(Seriousness) 판정
    is_serious BOOLEAN NOT NULL DEFAULT false,
    serious_reason VARCHAR(255),
    
    -- 인과관계 평가 (WHO-UMC / 식약처 기준)
    causality_grade VARCHAR(50) NOT NULL DEFAULT 'EVALUATING',
    causality_rationale TEXT,
    
    -- 규제기관 보고(식약처 / FDA MDR) 판정
    reportability_status VARCHAR(50) NOT NULL DEFAULT 'NOT_REPORTABLE',
    report_deadline DATE,
    authority_report_date DATE,
    authority_report_number VARCHAR(100),
    authority_feedback TEXT,
    
    -- 원인조사 (21 CFR 820.198(b))
    investigation_required BOOLEAN NOT NULL DEFAULT true,
    no_investigation_reason TEXT,
    investigation_summary TEXT,
    
    -- CAPA 연계 (16단계)
    capa_required BOOLEAN NOT NULL DEFAULT false,
    capa_status VARCHAR(50) NOT NULL DEFAULT 'NOT_REQUIRED',
    capa_number VARCHAR(50),
    capa_rationale TEXT,
    
    -- 진행 및 종결 상태
    evaluation_status VARCHAR(50) NOT NULL DEFAULT 'SUBMITTED',
    closed_by VARCHAR(100),
    closed_at TIMESTAMP,
    closure_remarks TEXT,
    
    -- 감사추적 메타데이터
    is_deleted BOOLEAN NOT NULL DEFAULT false,
    deleted_at TIMESTAMP,
    created_by VARCHAR(100),
    updated_by VARCHAR(100),
    created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP
);

-- 2. 불만/이상사례 후속 조치 과제 테이블 (complaint_action_items)
CREATE TABLE IF NOT EXISTS complaint_action_items (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    version BIGINT DEFAULT 0,
    evaluation_id BIGINT NOT NULL,
    action_item_number VARCHAR(50) NOT NULL,
    action_type VARCHAR(50) NOT NULL DEFAULT 'CUSTOMER_FEEDBACK',
    title VARCHAR(255) NOT NULL,
    description TEXT NOT NULL,
    assignee_name VARCHAR(100) NOT NULL,
    assignee_dept VARCHAR(100),
    due_date DATE NOT NULL,
    completed_date DATE,
    status VARCHAR(50) NOT NULL DEFAULT 'PENDING',
    action_result TEXT,
    verified_by VARCHAR(100),
    verified_at TIMESTAMP,
    verification_result VARCHAR(50) DEFAULT 'PENDING',
    
    -- 감사추적 메타데이터
    is_deleted BOOLEAN NOT NULL DEFAULT false,
    deleted_at TIMESTAMP,
    created_by VARCHAR(100),
    updated_by VARCHAR(100),
    created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    
    CONSTRAINT fk_complaint_action_eval FOREIGN KEY (evaluation_id) REFERENCES complaint_safety_evaluations(id) ON DELETE CASCADE
);

