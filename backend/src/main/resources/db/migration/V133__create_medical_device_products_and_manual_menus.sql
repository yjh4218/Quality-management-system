-- 1. 의료기기 품목 마스터 테이블 생성
CREATE TABLE IF NOT EXISTS medical_device_products (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    version BIGINT DEFAULT 0,
    item_code VARCHAR(50) NOT NULL,
    product_name VARCHAR(255) NOT NULL,
    english_product_name VARCHAR(255),
    model_name VARCHAR(100),
    device_classification VARCHAR(30) NOT NULL DEFAULT 'CLASS_I',
    intended_use TEXT,
    license_number VARCHAR(100),
    udi_di VARCHAR(50),
    udi_pi_type VARCHAR(100) DEFAULT 'LOT,EXPIRY',
    is_software BOOLEAN DEFAULT false,
    software_version VARCHAR(50),
    is_sterile BOOLEAN DEFAULT false,
    sterilization_method VARCHAR(50),
    storage_conditions VARCHAR(100),
    shelf_life_months INT,
    manufacturer VARCHAR(100),
    remarks TEXT,
    active BOOLEAN DEFAULT true,
    is_deleted BOOLEAN DEFAULT false,
    deleted_at TIMESTAMP,
    created_at TIMESTAMP,
    updated_at TIMESTAMP,
    CONSTRAINT uq_mdp_item_code UNIQUE (item_code)
);

CREATE INDEX IF NOT EXISTS idx_mdp_product_name ON medical_device_products(product_name);
CREATE INDEX IF NOT EXISTS idx_mdp_device_class ON medical_device_products(device_classification);
CREATE INDEX IF NOT EXISTS idx_mdp_udi_di ON medical_device_products(udi_di);

