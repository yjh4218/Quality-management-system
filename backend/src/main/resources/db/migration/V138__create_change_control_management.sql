-- 1. 변경요청서 마스터 테이블 (change_requests)
CREATE TABLE IF NOT EXISTS change_requests (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    version BIGINT DEFAULT 0,
    change_number VARCHAR(50) NOT NULL UNIQUE,
    title VARCHAR(255) NOT NULL,
    category VARCHAR(50) NOT NULL DEFAULT 'PRODUCT',
    urgency VARCHAR(30) NOT NULL DEFAULT 'STANDARD',
    status VARCHAR(50) NOT NULL DEFAULT 'DRAFT',
    target_item_name VARCHAR(200),
    item_code VARCHAR(100),
    initiator_name VARCHAR(100) NOT NULL,
    department VARCHAR(100) NOT NULL,
    request_date DATE NOT NULL,
    target_completion_date DATE,
    actual_completion_date DATE,
    change_reason TEXT NOT NULL,
    current_state TEXT NOT NULL,
    proposed_change TEXT NOT NULL,
    
    -- 영향평가 (Change Impact Assessment)
    regulatory_impact BOOLEAN DEFAULT false,
    regulatory_details TEXT,
    quality_safety_impact BOOLEAN DEFAULT false,
    quality_details TEXT,
    validation_required BOOLEAN DEFAULT false,
    validation_details TEXT,
    
    -- 양방향 추적성 연계 (Cross-Module Traceability)
    risk_assessment_id BIGINT,
    risk_assessment_code VARCHAR(50),
    dms_document_id BIGINT,
    dms_document_number VARCHAR(50),
    design_project_id BIGINT,
    design_project_code VARCHAR(50),
    
    -- CCB(Change Control Board) 심의 및 결정
    ccb_review_date DATE,
    ccb_attendees VARCHAR(255),
    ccb_summary TEXT,
    ccb_decision VARCHAR(30),
    ccb_conditions TEXT,
    
    -- 효과성 검증 (Effectiveness Check)
    effectiveness_required BOOLEAN DEFAULT true,
    effectiveness_due_date DATE,
    effectiveness_eval_date DATE,
    effectiveness_status VARCHAR(30) DEFAULT 'PENDING',
    effectiveness_summary TEXT,
    evaluator_name VARCHAR(100),
    
    -- 감사추적 메타데이터
    is_deleted BOOLEAN NOT NULL DEFAULT false,
    deleted_at TIMESTAMP,
    created_at TIMESTAMP,
    updated_at TIMESTAMP,
    created_by VARCHAR(100),
    updated_by VARCHAR(100)
);

CREATE INDEX IF NOT EXISTS idx_cr_change_number ON change_requests(change_number);
CREATE INDEX IF NOT EXISTS idx_cr_category ON change_requests(category);
CREATE INDEX IF NOT EXISTS idx_cr_status ON change_requests(status);
CREATE INDEX IF NOT EXISTS idx_cr_urgency ON change_requests(urgency);
CREATE INDEX IF NOT EXISTS idx_cr_is_deleted ON change_requests(is_deleted);
CREATE INDEX IF NOT EXISTS idx_cr_risk_assessment_id ON change_requests(risk_assessment_id);
CREATE INDEX IF NOT EXISTS idx_cr_dms_document_id ON change_requests(dms_document_id);
CREATE INDEX IF NOT EXISTS idx_cr_design_project_id ON change_requests(design_project_id);

-- 2. 변경실행 조치항목 테이블 (change_action_items)
CREATE TABLE IF NOT EXISTS change_action_items (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    version BIGINT DEFAULT 0,
    change_request_id BIGINT NOT NULL,
    action_order INTEGER NOT NULL DEFAULT 1,
    action_title VARCHAR(255) NOT NULL,
    action_details TEXT,
    assigned_person VARCHAR(100) NOT NULL,
    assigned_department VARCHAR(100),
    due_date DATE NOT NULL,
    completion_date DATE,
    status VARCHAR(30) NOT NULL DEFAULT 'PENDING',
    evidence_doc_url VARCHAR(500),
    verification_notes TEXT,
    is_deleted BOOLEAN NOT NULL DEFAULT false,
    created_at TIMESTAMP,
    updated_at TIMESTAMP,
    created_by VARCHAR(100),
    updated_by VARCHAR(100)
);

CREATE INDEX IF NOT EXISTS idx_cai_change_request_id ON change_action_items(change_request_id);
CREATE INDEX IF NOT EXISTS idx_cai_status ON change_action_items(status);
CREATE INDEX IF NOT EXISTS idx_cai_is_deleted ON change_action_items(is_deleted);

